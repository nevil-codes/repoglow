export function ThemeToggle() {
  const toggle = () => {
    const dark = document.documentElement.classList.toggle("dark");
    try {
      localStorage.setItem("theme", dark ? "dark" : "light");
    } catch {}
  };
  return (
    <button
      type="button"
      onClick={toggle}
      aria-label="Toggle theme"
      className="grid size-9 place-items-center rounded-xl border border-card-border bg-card text-muted backdrop-blur transition hover:text-fg"
    >
      <Icon.sun className="size-4 hidden dark:block" />
      <Icon.moon className="size-4 dark:hidden" />
    </button>
  );
}
