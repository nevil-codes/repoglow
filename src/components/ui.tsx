"use client";

import { useState, type ReactNode } from "react";

export function Card({ children, className = "" }: { children: ReactNode; className?: string }) {
  return (
    <div
      className={`rounded-2xl border border-card-border bg-card backdrop-blur-xl shadow-[0_1px_0_0_rgb(255_255_255/0.04)_inset] ${className}`}
    >
      {children}
    </div>
  );
}

export function CopyButton({ text, label = "Copy", className = "" }: { text: string; label?: string; className?: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <button
      type="button"
      onClick={async () => {
        await navigator.clipboard.writeText(text);
        setCopied(true);
        setTimeout(() => setCopied(false), 1500);
      }}
      className={`inline-flex items-center gap-1.5 rounded-lg border border-card-border bg-input px-2.5 py-1 text-xs font-medium text-muted transition hover:text-fg hover:border-accent-1/50 ${className}`}
    >
      {copied ? <Icon.check className="size-3.5 text-emerald-500" /> : <Icon.copy className="size-3.5" />}
      {copied ? "Copied" : label}
    </button>
  );
}

